import axios from "axios";
const api=axios.create({baseURL:(import.meta.env.VITE_API_BASE_URL||"https://datamark-pied.vercel.app").replace(/\/$/,""),timeout:30000});
export const apiBaseUrl=api.defaults.baseURL;
export const errorMessage=e=>e?.response?.data?.detail||e?.message||"Request failed";
const get=async(url,config)=>{const r=await api.get(url,config);return r.data};
const post=async(url,data)=>{const r=await api.post(url,data);return r.data};
export const getHealth=()=>get("/health");
export const getDatasets=()=>get("/datasets");
export const getDataset=id=>get(`/datasets/${encodeURIComponent(id)}`);
export const getProfile=id=>get(`/datasets/${encodeURIComponent(id)}/profile`);
export const uploadDataset=file=>{const f=new FormData();f.append("file",file);return post("/datasets/upload",f)};
export const cleanDataset=id=>post(`/datasets/${encodeURIComponent(id)}/clean`);
export const getTasks=(limit=100,domain="")=>get("/tasks",{params:{limit,...(domain?{domain}:{})}});
export const validateTasks=()=>post("/tasks/validate");
export const evaluateNumbers=payload=>post("/evaluate",payload);
export const getBenchmarks=()=>get("/benchmarks");
export const runBenchmark=()=>post("/benchmarks/run");
export const getReports=()=>get("/reports");
export const getMetrics=()=>get("/metrics");
